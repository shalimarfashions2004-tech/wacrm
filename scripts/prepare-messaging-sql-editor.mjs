import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const runtime = process.argv.includes('--runtime');
const sources = runtime
  ? ['supabase/migrations/051_managed_messaging_runtime.sql']
  : [
      'supabase/migrations/050_managed_messaging_budget.sql',
      'supabase/setup/shalimar-budget-policy.sql',
    ];
const output = resolve(
  root,
  `docs/sql/SHALIMAR_RUN_THIS_${runtime ? '051' : '050'}.sql`
);
const parts = await Promise.all(
  sources.map((path) => readFile(resolve(root, path), 'utf8'))
);
await mkdir(resolve(root, 'docs/sql'), { recursive: true });
await writeFile(
  output,
  [
    '-- SHALIMAR: paste this ENTIRE file into a new Supabase SQL Editor query.',
    '-- Generated by scripts/prepare-messaging-sql-editor.mjs; edit the sources instead.',
    runtime
      ? '-- Adds runtime checks to the installed INR 1,000/month policy. Sends no messages.'
      : '-- Installs controls and a disabled INR 1,000/month policy. Sends no messages.',
    '-- Existing Inbox replies, credentials and phone registration are untouched.',
    runtime
      ? '-- Prerequisite: SHALIMAR_RUN_THIS_050.sql has already completed successfully.'
      : '-- Prerequisites: the existing WACRM schema including migrations 043 and 046.',
    '-- The entire transaction rolls back if the saved sender does not match.',
    'BEGIN;',
    "SET LOCAL lock_timeout = '5s';",
    "SET LOCAL statement_timeout = '60s';",
    ...(runtime
      ? [
          `DO $$ BEGIN
  IF (SELECT count(*) FROM public.messaging_budget_policies p
    JOIN public.whatsapp_config c ON c.account_id=p.account_id
    WHERE c.phone_number_id='1391671597361924' AND c.waba_id='28787952197487898'
      AND p.phone_number_id=c.phone_number_id AND p.waba_id=c.waba_id
      AND p.monthly_limit_paise=100000) <> 1 THEN
    RAISE EXCEPTION 'Setup stopped: matching installed Shalimar INR 1000 policy not found';
  END IF;
END $$;`,
        ]
      : []),
    ...parts,
    ...(runtime
      ? [
          `SELECT '051 installed' AS migration,
  p.monthly_limit_paise / 100 AS monthly_limit_inr,
  COALESCE((SELECT SUM(reserved_paise) FROM public.messaging_delivery_ledger l
    WHERE l.account_id=p.account_id AND l.budget_month=date_trunc('month',now() AT TIME ZONE 'Asia/Kolkata')::date),0)/100.0 AS reserved_this_month_inr,
  CASE WHEN p.enabled THEN 'ON - separate saved-source approval still required' ELSE 'OFF' END AS managed_delivery,
  'Existing credentials and Inbox replies unchanged' AS connection,
  'Each saved campaign or workflow requires approval in CRM' AS next_step
FROM public.messaging_budget_policies p
WHERE p.phone_number_id='1391671597361924' AND p.waba_id='28787952197487898';`,
        ]
      : []),
    'COMMIT;',
    '',
  ].join('\n')
);
console.log(output);
