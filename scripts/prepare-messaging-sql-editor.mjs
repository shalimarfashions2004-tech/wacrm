import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const sources = [
  'supabase/migrations/050_managed_messaging_budget.sql',
  'supabase/setup/shalimar-budget-policy.sql',
];
const output = resolve(root, 'docs/sql/SHALIMAR_RUN_THIS_050.sql');
const parts = await Promise.all(
  sources.map((path) => readFile(resolve(root, path), 'utf8'))
);
await mkdir(resolve(root, 'docs/sql'), { recursive: true });
await writeFile(
  output,
  [
    '-- SHALIMAR: paste this ENTIRE file into a new Supabase SQL Editor query.',
    '-- Generated by scripts/prepare-messaging-sql-editor.mjs; edit the sources instead.',
    '-- Installs controls and a disabled INR 1,000/month policy. Sends no messages.',
    '-- Existing Inbox replies, credentials and phone registration are untouched.',
    '-- Prerequisites: the existing WACRM schema including migrations 043 and 046.',
    '-- The entire transaction rolls back if the saved sender does not match.',
    'BEGIN;',
    "SET LOCAL lock_timeout = '5s';",
    "SET LOCAL statement_timeout = '60s';",
    ...parts,
    'COMMIT;',
    '',
  ].join('\n')
);
console.log(output);
